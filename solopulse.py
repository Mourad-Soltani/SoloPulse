import json
import urllib.request
import urllib.error
import socket
from datetime import datetime
from typing import Dict, List, Any

class HealthChecker:
    """Minimal endpoint health checker."""
    
    def __init__(self, timeout: int = 5):
        self.timeout = timeout
    
    def check_url(self, url: str) -> Dict[str, Any]:
        """Check a single URL and return status."""
        start = datetime.now()
        try:
            req = urllib.request.Request(url, headers={'User-Agent': 'SoloPulse/1.0 (Mourad.Soltani)'})
            with urllib.request.urlopen(req, timeout=self.timeout) as response:
                status_code = response.getcode()
                elapsed = (datetime.now() - start).total_seconds() * 1000
                return {
                    'url': url,
                    'status': 'up' if 200 <= status_code < 400 else 'down',
                    'code': status_code,
                    'latency_ms': round(elapsed, 1),
                    'checked_at': datetime.utcnow().isoformat() + 'Z'
                }
        except (urllib.error.URLError, urllib.error.HTTPError, socket.timeout, Exception) as e:
            elapsed = (datetime.now() - start).total_seconds() * 1000
            return {
                'url': url,
                'status': 'down',
                'code': 0,
                'error': str(e),
                'latency_ms': round(elapsed, 1),
                'checked_at': datetime.utcnow().isoformat() + 'Z'
            }
    
    def check_all(self, endpoints: List[Dict[str, str]]) -> List[Dict[str, Any]]:
        """Check multiple endpoints."""
        results = []
        for ep in endpoints:
            result = self.check_url(ep['url'])
            result['name'] = ep.get('name', ep['url'])
            results.append(result)
        return results

def generate_status_html(results: List[Dict[str, Any]], title: str = "SoloPulse Status") -> str:
    """Generate a simple static HTML status page."""
    up_count = sum(1 for r in results if r['status'] == 'up')
    total = len(results)
    overall = "All Systems Operational" if up_count == total else f"{up_count}/{total} Operational"
    
    rows = ""
    for r in results:
        status_class = "up" if r['status'] == 'up' else "down"
        rows += f"""
        <tr class="{status_class}">
            <td>{r['name']}</td>
            <td>{r['status'].upper()}</td>
            <td>{r.get('code', 'N/A')}</td>
            <td>{r.get('latency_ms', 'N/A')} ms</td>
            <td>{r['checked_at']}</td>
        </tr>
        """
    
    html = f"""<!DOCTYPE html>
<html lang="en">
<head>
    <meta charset="UTF-8">
    <title>{title}</title>
    <style>
        body {{ font-family: system-ui, sans-serif; max-width: 800px; margin: 2rem auto; padding: 1rem; }}
        h1 {{ color: #333; }}
        .overall {{ font-size: 1.2rem; padding: 1rem; border-radius: 8px; background: #e8f5e9; }}
        table {{ width: 100%; border-collapse: collapse; margin-top: 1rem; }}
        th, td {{ padding: 0.5rem; text-align: left; border-bottom: 1px solid #ddd; }}
        .up {{ background: #e8f5e9; }}
        .down {{ background: #ffebee; }}
        footer {{ margin-top: 2rem; font-size: 0.8rem; color: #666; }}
    </style>
</head>
<body>
    <h1>{title}</h1>
    <div class="overall">{overall}</div>
    <table>
        <thead>
            <tr><th>Service</th><th>Status</th><th>Code</th><th>Latency</th><th>Checked</th></tr>
        </thead>
        <tbody>
            {rows}
        </tbody>
    </table>
    <footer>Generated by SoloPulse — Mourad.Soltani</footer>
</body>
</html>"""
    return html

def main():
    import argparse
    import sys
    
    parser = argparse.ArgumentParser(description="SoloPulse - Health monitor for solo SaaS")
    parser.add_argument("--config", required=True, help="JSON config file with endpoints")
    parser.add_argument("--output", default="status.html", help="Output HTML file")
    args = parser.parse_args()
    
    with open(args.config) as f:
        config = json.load(f)
    
    checker = HealthChecker()
    results = checker.check_all(config.get('endpoints', []))
    html = generate_status_html(results, config.get('title', 'SoloPulse Status'))
    
    with open(args.output, 'w') as f:
        f.write(html)
    
    print(f"Status page written to {args.output}")
    print(json.dumps(results, indent=2))

if __name__ == "__main__":
    main()

